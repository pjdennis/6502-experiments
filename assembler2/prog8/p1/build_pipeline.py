#!/usr/bin/env python3
"""Generate the self-hosting PIPELINE: p1_pass1.p8 (front-end + symbols + AST
dump) and p1_pass2.p8 (AST load + codegen).  Additive -- does not touch the
monolith p1.p8.

The monolith doesn't fit p1.p8 in 64 KB (front-end ~22 KB + codegen ~33 KB +
program-wide arenas ~15 KB).  Splitting into two <=64 KB passes (the repo's own
asm00->asm17 bootstrap pattern) fixes that, stays ordinary upstream-compatible
Prog8, and needs no banking.

Reuses build_p1.py: 131 of its 134 codegen subs are PURE (operate only on the
node arrays) and are emitted into pass 2 verbatim; only register_subs / emit_subs
/ cg_skip_decl (which re-parse source) are replaced by load-driven versions.
"""
import re
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
STMT = HERE / "stmt.p8"
import sys
spec = importlib.util.spec_from_file_location("build_p1", str(HERE / "build_p1.py"))
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)

# ---- split stmt.p8 front-end into the module-state preamble + named subs ----
fe_all = STMT.read_text()
ser_idx = fe_all.index("; ---- serialization ----")
fe = fe_all[:ser_idx]

# Everything before the first `sub ` is the preamble (consts + module-state
# array declarations); both passes need it.
first_sub = re.search(r'(?m)^sub \w+', fe).start()
fe_preamble = fe[:first_sub]

def split_subs(text):
    """-> list of (name, full_source_including_header) in order."""
    out = []
    for m in re.finditer(r'(?m)^sub (\w+)', text):
        out.append((m.group(1), m.start()))
    res = []
    for i, (name, start) in enumerate(out):
        end = out[i + 1][1] if i + 1 < len(out) else len(text)
        res.append((name, text[start:end].rstrip() + "\n"))
    return res

fe_subs = split_subs(fe[first_sub:])

# Pass-1-only stmt.p8 subs: the lexer + parser.  Everything else (I/O, the out_*
# emitters, decimal output, new_node, cons helpers, reset_nodes/arena) is shared.
PARSER_PREFIXES = ("parse_", "read_", "lex_", "push_token", "cur_kind",
                   "advance", "is_digit", "is_alpha", "is_alnum", "shunt",
                   "classify_", "cn_len", "intern_name", "skip_")
PARSER_EXACT = {"const_type_tag", "type_tag", "is_type_kw", "decode_escape_val",
                "pop_op", "push_op", "apply_op", "prec_of", "is_binop_tok",
                "is_unop_tok", "op_prec", "make_binop", "make_unop",
                "next_raw_token", "stmt_dispatch", "close_index",
                "handle_directive", "append_ident_to_pathbuf", "is_hexdig"}

# read_src / peek_src are the file I/O byte readers -- BOTH passes need them
# (pass 2 reads the dumped AST through read_src). Not parser subs.
IO_SHARED = {"read_src", "peek_src"}

def is_parser_sub(name):
    if name in IO_SHARED:
        return False
    if name in PARSER_EXACT:
        return True
    return any(name.startswith(p) for p in PARSER_PREFIXES)

fe_shared = [(n, s) for n, s in fe_subs if not is_parser_sub(n)]
fe_parser = [(n, s) for n, s in fe_subs if is_parser_sub(n)]

# ---- split build_p1.codegen into the sym_state-less preamble + subs + main ----
cg = bp.codegen
# the codegen string starts with a comment block then subs; find first sub
cg_first = re.search(r'(?m)^sub \w+', cg).start()
cg_preamble = cg[:cg_first]
# the trailing `main {{...}}` driver -- in the generated file it's `main {`
mdrv = re.search(r'(?m)^main \{', cg)
cg_subs_text = cg[cg_first:mdrv.start()]
cg_subs = split_subs(cg_subs_text)

# subs that re-parse source -> replaced in pass 2 by load-driven versions
CG_REPLACE = {"register_subs", "emit_subs", "cg_skip_decl"}
cg_pure = [(n, s) for n, s in cg_subs if n not in CG_REPLACE]

print(f"stmt.p8: {len(fe_shared)} shared subs, {len(fe_parser)} parser subs")
print(f"codegen: {len(cg_pure)} pure subs reused, {len(CG_REPLACE)} replaced")

# ---- extract the codegen sym_state block from the committed monolith p1.p8 ----
p1_text = (HERE / "p1.p8").read_text()
ss_start = p1_text.index("; ---- codegen symbol table (persistent across passes) ----")
ss_end = p1_text.index("; serializer work stack")
sym_state = p1_text[ss_start:ss_end].replace("ubyte sym_count","uword sym_count")
# the pipeline needs one extra per-sub array: each sub's parsed node ptr, so
# pass 2 can emit_sub(sub_snode[i]) from the loaded AST.
sym_state += "uword[32] sub_snode\nuword resident_sym_count\nuword rec_kind\nuword rec_snode\n"

MARKER = "; serializer work stack"
assert MARKER in fe_preamble, "marker not in stmt.p8 preamble"
pass2_preamble = fe_preamble.replace(MARKER, sym_state + MARKER, 1)
pass2_preamble = bp.shrink_arenas(pass2_preamble)

HEADER = ("; ---- GENERATED by build_pipeline.py -- DO NOT EDIT ----\n"
          "; pass 2 of the self-hosting pipeline: load the dumped AST + codegen.\n\n")

# ---- the binary AST dump/load (generic byte I/O over the codegen arrays) ----
DUMP_LOAD_COMMON = """
sub d16(uword v) { out_byte(lsb(v)) out_byte(lsb(v >> 8)) }
"""

DUMP_STATE = """
; pass 1: program-wide state (no nodes -- those stream per-sub afterwards).
sub dump_global() {
    d16(prog_address)
    out_byte(prog_target)
    uword i
    uword rc
    rc = 0
    i = 0
    repeat { if i >= sym_count { break } if sym_scope[i] == 0 { rc = rc + 1 } else { if sym_mkind[i] == 1 { rc = rc + 1 } } i = i + 1 }
    d16(rc)
    i = 0
    repeat {
        if i >= sym_count { break }
        ubyte keep
        keep = 0
        if sym_scope[i] == 0 { keep = 1 }
        if sym_mkind[i] == 1 { keep = 1 }
        if keep != 0 {
            d16(sym_ident[i]) out_byte(sym_type[i]) d16(sym_addr[i]) d16(sym_scope[i])
            out_byte(sym_mkind[i]) out_byte(sym_is_const[i]) d16(sym_cval[i]) d16(sym_arr_size[i])
        }
        i = i + 1
    }
    d16(sub_count)
    i = 0
    repeat {
        if i >= sub_count { break }
        d16(sub_name[i]) out_byte(sub_kind[i]) out_byte(sub_ret[i]) d16(sub_addr[i])
        i = i + 1
    }
    d16(ident_pool_len)
    i = 0
    repeat { if i >= ident_pool_len { break } out_byte(ident_pool[i]) i = i + 1 }
    d16(str_pool_len)
    i = 0
    repeat { if i >= str_pool_len { break } out_byte(str_pool[i]) i = i + 1 }
    d16(str_count)
    i = 0
    repeat { if i >= str_count { break } d16(str_off[i]) d16(str_len[i]) i = i + 1 }
}
; one sub's AST record: kind(1) snode(2) node_count(2) nodes cons_count(2) cons.
sub dump_record(ubyte kind, uword snode) {
    out_byte(kind)
    d16(snode)
    uword i
    uword nm
    nm = node_a[snode]
    uword lc
    lc = 0
    i = 0
    repeat { if i >= sym_count { break } if sym_scope[i] == nm { if sym_mkind[i] == 2 { lc = lc + 1 } } i = i + 1 }
    d16(lc)
    i = 0
    repeat {
        if i >= sym_count { break }
        if sym_scope[i] == nm {
            if sym_mkind[i] == 2 {
                d16(sym_ident[i]) out_byte(sym_type[i]) d16(sym_addr[i]) d16(sym_scope[i])
                out_byte(sym_mkind[i]) out_byte(sym_is_const[i]) d16(sym_cval[i]) d16(sym_arr_size[i])
            }
        }
        i = i + 1
    }
    d16(node_count)
    i = 0
    repeat {
        if i >= node_count { break }
        out_byte(node_kind[i]) out_byte(node_op[i])
        d16(node_a[i]) d16(node_b[i]) d16(node_c[i]) d16(node_d[i])
        i = i + 1
    }
    d16(cons_count)
    i = 0
    repeat {
        if i >= cons_count { break }
        d16(cons_val[i]) d16(cons_next[i])
        i = i + 1
    }
}
"""

ZP_TEXT = """
sub copy_zp_text() {
    repeat { ubyte b
        b = read_src()
        if b == 0 { break }
        out_byte(b)
    }
}
sub skip_zp_text() {
    repeat { ubyte b
        b = read_src()
        if b == 0 { break }
    }
}
sub copy_memvar_text() {
    repeat { ubyte b
        b = read_src()
        if b == 0 { break }
        out_byte(b)
    }
}
sub skip_memvar_text() {
    repeat { ubyte b
        b = read_src()
        if b == 0 { break }
    }
}
"""

LOAD_STATE = """
sub l16() -> uword {
    uword lo
    lo = read_src()
    uword hi
    hi = read_src()
    return lo | (hi << 8)
}
sub load_global() {
    prog_address = l16()
    prog_target = read_src()
    uword i
    sym_count = l16()
    i = 0
    repeat {
        if i >= sym_count { break }
        sym_ident[i] = l16() sym_type[i] = read_src() sym_addr[i] = l16() sym_scope[i] = l16()
        sym_mkind[i] = read_src() sym_is_const[i] = read_src() sym_cval[i] = l16() sym_arr_size[i] = l16()
        i = i + 1
    }
    resident_sym_count = sym_count
    sub_count = l16()
    i = 0
    repeat {
        if i >= sub_count { break }
        sub_name[i] = l16() sub_kind[i] = read_src() sub_ret[i] = read_src() sub_addr[i] = l16()
        i = i + 1
    }
    ident_pool_len = l16()
    i = 0
    repeat { if i >= ident_pool_len { break } ident_pool[i] = read_src() i = i + 1 }
    str_pool_len = l16()
    i = 0
    repeat { if i >= str_pool_len { break } str_pool[i] = read_src() i = i + 1 }
    str_count = l16()
    i = 0
    repeat { if i >= str_count { break } str_off[i] = l16() str_len[i] = l16() i = i + 1 }
}
; load one record's nodes into the (reset) node arena; returns the snode.
sub load_record() {
    rec_kind = read_src()
    if rec_kind == $ff { return }
    rec_snode = l16()
    uword i
    sym_count = resident_sym_count
    uword lc
    lc = l16()
    i = 0
    repeat {
        if i >= lc { break }
        sym_ident[sym_count] = l16() sym_type[sym_count] = read_src() sym_addr[sym_count] = l16() sym_scope[sym_count] = l16()
        sym_mkind[sym_count] = read_src() sym_is_const[sym_count] = read_src() sym_cval[sym_count] = l16() sym_arr_size[sym_count] = l16()
        sym_count = sym_count + 1
        i = i + 1
    }
    node_count = l16()
    i = 0
    repeat {
        if i >= node_count { break }
        node_kind[i] = read_src() node_op[i] = read_src()
        node_a[i] = l16() node_b[i] = l16() node_c[i] = l16() node_d[i] = l16()
        i = i + 1
    }
    cons_count = l16()
    i = 0
    repeat {
        if i >= cons_count { break }
        cons_val[i] = l16() cons_next[i] = l16()
        i = i + 1
    }
}
"""


