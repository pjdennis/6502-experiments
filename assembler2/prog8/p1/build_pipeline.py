def reachable(subs_dict, driver_text):
    """names of subs reachable from the main driver (transitive)."""
    import re as _re
    seeds = set(_re.findall(r'\b(\w+)\s*\(', driver_text))
    live=set(); work=[x for x in seeds if x in subs_dict]
    while work:
        n=work.pop()
        if n in live: continue
        live.add(n)
        for c in set(_re.findall(r'\b(\w+)\s*\(', subs_dict[n])):
            if c in subs_dict and c not in live: work.append(c)
    return live

def emit_pass2():
    pool = dict(fe_shared) | dict(cg_pure)
    live = reachable(pool, PASS2_DRIVERS + PASS2_MAIN + DUMP_LOAD_COMMON + LOAD_STATE + ZP_TEXT)
    parts = [HEADER, pass2_preamble]
    for n, body in fe_shared + cg_pure:
        if n in live:
            parts.append(body)
    parts.append(DUMP_LOAD_COMMON)
    parts.append(LOAD_STATE)
    parts.append(ZP_TEXT)
    parts.append(PASS2_DRIVERS)
    parts.append(PASS2_MAIN)
    text = "\n".join(parts)
    (HERE / "p1_pass2.p8").write_text(text)
    print(f"wrote p1_pass2.p8 ({len(text.splitlines())} lines)")

def emit_pass1():
    cg_map = dict(cg_subs)
    p1_preamble = fe_preamble.replace(MARKER, sym_state + MARKER, 1)
    p1_preamble = bp.shrink_arenas(p1_preamble)
    parts = [HEADER.replace("pass 2", "pass 1"), p1_preamble]
    for _, body in fe_subs:
        parts.append(body)
    p1_seeds = "build_symbols() walk_locals() push_walk_block() push_walk_when() find_sym() reverse_cons() cg_skip_decl() emit_zp_bindings() emit_memvars() emit_sym_mangled() " + cg_map["register_subs"]
    p1_live = reachable(cg_map, p1_seeds)
    for n, body in cg_subs:
        if n in p1_live and n != "register_subs":
            parts.append(body)
    parts.append(DUMP_LOAD_COMMON)
    parts.append(cg_map["register_subs"])
    parts.append(DUMP_STATE)
    parts.append(PASS1_MAIN)
    text = "\n".join(parts)
    (HERE / "p1_pass1.p8").write_text(text)
    print(f"wrote p1_pass1.p8 ({len(text.splitlines())} lines)")

if __name__ == "__main__":
    emit_pass1()
    emit_pass2()
